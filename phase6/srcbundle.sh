#!/bin/bash
# srcbundle
#	OpenTTD's source for Plan 9 as one file: work/openttd-<version>-src.tgz,
#	the C that the pipeline generated from the release (../phase2/work/tu:
#	run ../phase2/buildtu.sh first), the hand-written runtime it links
#	with (../phase0/plan9, ../phase0/eh), FreeType's source, the data, the
#	licences, and an mkfile that builds and installs it with the
#	system's own compilers on 9front or 9legacy (amd64).  README.Plan9
#	(srcbundle.README) says that the C is generated, how, and from
#	what: this repository's commit and the tools' versions are filled in.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/.." && pwd)
. "$repo/phase1/common.sh"
tu=$repo/phase2/work/tu
[ -f "$tu/mkfile" ] && [ -f "$tu/config.9front" ] || fatal "no $tu: run ../phase2/buildtu.sh"
for s in opengfx opensfx openmsx; do
	[ -d "$data/openttd/baseset/$s" ] || fatal "no $s: run ../phase1/setup.sh"
done

version=$(cut -f1 "$work/ottdrev")
ottdhash=$(cut -f4 "$work/ottdrev")
commit=$(git -C "$repo" rev-parse --short=12 HEAD)
dirty=
git -C "$repo" diff --quiet HEAD -- || dirty=" (with uncommitted changes)"
b=$here/work/src
d=$b/openttd-$version-src
rm -rf "${b:?}"
mkdir -p "$d/tu" "$d/runtime/plan9" "$d/runtime/eh" "$d/doc"

# the generated C: the units the mkfile names (UNITS), with the mkfile,
# the rules, and configurations whose paths are the bundle's
units=$(awk '/^UNITS=/{f=1; next} f{if($0 !~ /\\$/) f=0; gsub(/\\/,""); print}' "$tu/mkfile")
for u in $units; do
	cp "$tu/$u.c" "$d/tu/$u.c"
done
cp "$tu/mkfile" "$tu/units.link" "$tu/rules.9front" "$tu/rules.9legacy" "$d/tu/"
for s in 9front 9legacy; do
	sed -e 's|^P0=.*|P0=../runtime|' \
	    -e 's|^LIBS=.*|LIBS=../freetype/libfreetype.a$O|' \
	    -e 's|^# generated by build.sh: do not edit|# generated by build.sh, for the source bundle: do not edit|' \
		"$tu/config.$s" >"$d/tu/config.$s"
done

# the hand-written runtime: what the two configurations name, the
# headers, the cbe shim
rt=$(sed -n 's/^RUNTIME=//p' "$tu/config.9front" "$tu/config.9legacy" | tr ' ' '\n' | sort -u)
for r in $rt; do
	if [ -f "$repo/phase0/plan9/$r.c" ]; then
		cp "$repo/phase0/plan9/$r.c" "$d/runtime/plan9/"
	elif [ -f "$repo/phase0/eh/$r.c" ]; then
		cp "$repo/phase0/eh/$r.c" "$d/runtime/eh/"
	else
		fatal "runtime part $r: no source"
	fi
done
cp "$repo"/phase0/plan9/{thread.h,net.h,p9audio.h,p9draw.h} "$d/runtime/plan9/"
cp -r "$repo/phase0/plan9/shim" "$d/runtime/plan9/shim"
cp "$repo/phase0/eh/eh_rt.h" "$d/runtime/eh/"
cp -r "$repo/phase0/eh/plan9" "$d/runtime/eh/plan9"

# FreeType's source, with its Plan 9 mkfile
rsync -a --exclude .git --exclude '*.6' --exclude '*.a6' --exclude p9ftopt.h \
	"$freetype/" "$d/freetype/"

# the data, as the binary bundle's
for x in lang ai game media bin baseset; do
	cp -rL "$work/build-p9/$x" "$d/$x"
done
for s in opengfx opensfx openmsx; do
	cp -rL "$data/openttd/baseset/$s" "$d/baseset/$s"
done

# the licences: OpenTTD's and its third-party code's, and of what was
# translated with it (libc++, libc++abi, zlib, liblzma) or is linked
# (FreeType)
cp "$ref/COPYING.md" "$d/doc/COPYING.md"
for l in fmt/LICENSE.rst nlohmann/LICENSE.MIT; do
	cp "$ref/src/3rdparty/$l" "$d/doc/3rdparty-$(dirname "$l")-$(basename "$l")"
done
llvm=$repo/phase0/work/llvm-src
cp "$llvm/libcxx/LICENSE.TXT" "$d/doc/libcxx-LICENSE.TXT"
cp "$llvm/libcxxabi/LICENSE.TXT" "$d/doc/libcxxabi-LICENSE.TXT"
cp "$zlib/LICENSE" "$d/doc/zlib-LICENSE"
cp "$xz/COPYING" "$d/doc/xz-COPYING"
cp "$xz/COPYING.0BSD" "$d/doc/xz-COPYING.0BSD"
cp "$freetype/docs/FTL.TXT" "$d/doc/FreeType-FTL.TXT"
cp "$ref/README.md" "$d/README.md"

# the mkfile, and README.Plan9 with what it was made from
cp "$here/srcbundle.mkfile" "$d/mkfile"
clangv=$(clang-17 --version | sed 1q)
llvmv=$(git -C "$llvm" describe --tags 2>/dev/null || git -C "$llvm" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
cbev=$(git -C "$repo/phase0/work/llvm-cbe" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
sed -e "s|@VERSION@|$version|g" -e "s|@OTTDHASH@|$ottdhash|g" \
    -e "s|@COMMIT@|$commit$dirty|g" -e "s|@CLANG@|$clangv|g" \
    -e "s|@LLVM@|$llvmv|g" -e "s|@CBE@|$cbev|g" \
    -e "s|@FREETYPE@|$fttag|g" -e "s|@ZLIB@|$zlibtag|g" -e "s|@XZ@|$xztag|g" \
	"$here/srcbundle.README" >"$d/README.Plan9"

tgz=$here/work/openttd-$version-src.tgz
tar -C "$b" --format=ustar --owner=0 --group=0 --numeric-owner -czf "$tgz" "openttd-$version-src"
echo "$tgz: $(du -h "$tgz" | cut -f1); $(echo $units | wc -w) generated units, $(ls "$d/runtime/plan9" "$d/runtime/eh" | grep -c '\.c$') runtime sources"
