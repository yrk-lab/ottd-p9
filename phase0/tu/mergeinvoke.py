#!/usr/bin/env python3
# mergeinvoke invoke.c unit.inv...
#	One file of exception wrappers for separately translated units:
#	the union of their mkinvoke.py output, by the /*@ name */ line that
#	starts each struct and wrapper (the same name is the same code):
#	structs in the order first seen (mkinvoke.py writes a struct after
#	those it contains), wrappers in name order.  invoke.c is written
#	only if it changed.
import sys

if len(sys.argv) < 2:
	sys.exit("usage: mergeinvoke invoke.c unit.inv...")
structs, funcs = {}, {}
for f in sys.argv[2:]:
	text = open(f).read()
	parts = text.split("/*@ ")
	for p in parts[1:]:
		name, body = p.split(" */\n", 1)
		body = body.split("#ifdef __GNUC__")[0]	# the pack pragmas around the structs
		if name.startswith("struct "):
			structs.setdefault(name, body)
		else:
			funcs.setdefault(name, body)
out = ["/* generated by mergeinvoke.py: do not edit */\n#include \"eh_sys.h\"\n#include \"eh_rt.h\"\n\n"]
if structs:
	out.append("#ifdef __GNUC__\n#pragma pack(push, 1)\n#else\n#pragma pack on\n#endif\n")
	out += list(structs.values())	# as first seen: each after the structs it contains
	out.append("#ifdef __GNUC__\n#pragma pack(pop)\n#else\n#pragma pack off\n#endif\n\n")
out += [funcs[n] for n in sorted(funcs)]
new = "".join(out)
try:
	old = open(sys.argv[1]).read()
except FileNotFoundError:
	old = None
if new != old:
	open(sys.argv[1], "w").write(new)
print("mergeinvoke: %d structs, %d wrappers" % (len(structs), len(funcs)))
