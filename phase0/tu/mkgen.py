#!/usr/bin/env python3
# mkgen units dir llvm-cbe
#	Write the two mkfiles of a separately translated program in dir,
#	from units (one "name path.bc" a line, link order):
#	trans.mk	translation, on Linux with plan9port's mk: name.syms
#			(symtab.py) and name.c (unit.sh) from each unit's IR;
#			targets syms and c (see build.sh: homes.py runs
#			between them, outside mk).  name.tr records the
#			translation; name.c's time is when its content last
#			changed, which is what the compilation goes by.
#	mkfile		compilation, with Plan 9's mk on 9front or plan9port's
#			on Linux (goken, linux): mk SYS=9front, SYS=goken
#			or SYS=linux includes
#			config.$SYS (CC, LD, CFLAGS, the runtime's place and
#			OBJ, the object directory, so the systems' objects
#			never mix; RUNTIME, the runtime's files in $P0/plan9
#			and $P0/eh; TARG) and rules.$SYS (rules of its
#			own), and builds $OBJ/$TARG from every
#			name.c, invoke.c, ctors.c and the runtime
#	units.link	the units' objects for the link, in order
#	Each is written only if it changed.
import os
import sys

if len(sys.argv) != 4:
	sys.exit("usage: mkgen units dir llvm-cbe")
units = [l.split() for l in open(sys.argv[1]) if l.strip()]
d = sys.argv[2]
cbe = sys.argv[3]
tu = os.path.dirname(os.path.abspath(__file__))
names = [n for n, _ in units]
if len(set(names)) != len(names):
	sys.exit("mkgen: unit names are not unique")


def write(name, text):
	p = os.path.join(d, name)
	try:
		old = open(p).read()
	except FileNotFoundError:
		old = None
	if text != old:
		open(p, "w").write(text)


def wrap(words, indent="\t"):
	lines, cur = [], ""
	for w in words:
		if len(cur) + len(w) > 70:
			lines.append(cur)
			cur = ""
		cur += (" " if cur else "") + w
	lines.append(cur)
	return (" \\\n" + indent).join(lines)


t = ["# generated by mkgen.py: do not edit\n",
	"MKSHELL=$PLAN9/bin/rc\n",
	"TU=%s\n" % tu,
	# the translator: a change to it translates every unit again (and
	# unit.sh leaves the C files that come out the same alone)
	"TOOLS=$TU/unit.sh $TU/localize.py %s/plan9/lower.py %s/eh/mkinvoke.py %s/eh/pmf.py %s\n\n"
		% (os.path.dirname(tu), os.path.dirname(tu), os.path.dirname(tu), cbe),
	"syms:V: \\\n\t%s\n\n" % wrap(n + ".syms" for n in names),
	"c:V: \\\n\t%s\n\n" % wrap(n + ".tr" for n in names)]
for n, bc in units:
	t.append("%s.syms: %s\n\tpython3 $TU/symtab.py $prereq $target\n" % (n, bc))
	t.append("%s.tr: %s %s.home $TOOLS\n\t$TU/unit.sh %s %s.home %s . && touch $target\n" % (n, bc, n, bc, n, n))
write("trans.mk", "".join(t))

m = ["# generated by mkgen.py: do not edit\n",
	# here, not in config.$SYS: plan9port's mk takes MKSHELL only from
	# the mkfile itself (set in an included file, the recipes ran in
	# sh, $prereq through the environment, cut short when long).  On
	# 9front $PLAN9 is empty: /bin/rc
	"MKSHELL=$PLAN9/bin/rc\n",
	"<config.$SYS\n\n",
	"UNITS=\\\n\t%s\n\n" % wrap(names + ["invoke", "ctors"]),
	"$OBJ/$TARG: ${UNITS:%=$OBJ/%.$O} ${RUNTIME:%=$OBJ/%.$O}\n",
	# the objects from a file, not $prereq: plan9port's mk cut a list
	# this long (19 KB) short
	"\t$LD $LDFLAGS -o $target `{for(n in `{cat units.link} $RUNTIME) echo $OBJ/$n.$O} $LIBS\n\n",
	"$OBJ/invoke.$O: invoke.c\n\t$CC $RTCFLAGS -o $target invoke.c\n\n",
	"$OBJ/%.$O: %.c\n\t$CC $CFLAGS -o $target $stem.c\n\n",
	"$OBJ/%.$O: $P0/plan9/%.c\n\t$CC $RTCFLAGS -o $target $P0/plan9/$stem.c\n\n",
	"$OBJ/%.$O: $P0/eh/%.c\n\t$CC $RTCFLAGS -o $target $P0/eh/$stem.c\n\n",
	"$OBJ/%.$O: $P0/%.c\n\t$CC $RTCFLAGS -o $target $P0/$stem.c\n\n",
	# the system's own rules, after the default target
	"<rules.$SYS\n"]
write("mkfile", "".join(m))
write("units.link", "".join(n + "\n" for n in names + ["invoke", "ctors"]))
