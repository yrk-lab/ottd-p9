#!/bin/bash
# build units dir targ
#	Translate a program unit by unit and build it with goken, keeping
#	the source's structure: one unit's change rebuilds that unit.
#	units: one "name path.bc" a line, in link order (the program's;
#	the libc++ modules it needs are added here, as libunits.py picks
#	them).  In dir (flat): name.syms, name.home, name.c, name.inv,
#	name.ctors, invoke.c, ctors.c, trans.mk and mkfile (mkgen.py),
#	config.$SYS and rules.$SYS for goken, 9front and linux, and the
#	builds for $sys (default goken) in obj.$sys/ (mk SYS=$sys);
#	9front builds the same dir with mk SYS=9front.
#	Steps, each leaving a file's time alone when its content is the
#	same: the symbol tables (mk -f trans.mk syms), the shared symbols'
#	homes (homes.py, between the mk runs: mk would count its untouched
#	outputs as new), the translation (mk -f trans.mk c), the exception
#	wrappers and constructor table, the compilation (mk).
#	$NPROC jobs at a time (default: the processors).
set -uo pipefail
. "$(dirname "$0")/../common.sh"
[ $# -eq 3 ] || fatal "usage: build units dir targ"
units=$(realpath "$1")
dir=$2
targ=$3
tu=$top/tu
export PLAN9=${PLAN9:-$HOME/plan9}
export NPROC=${NPROC:-$(nproc)}
mk=$PLAN9/bin/mk
[ -x "$mk" ] || fatal "no plan9port in $PLAN9"
[ -f "$libir/stamp" ] || "$top/build_libcxx.sh" >/dev/null || fatal "no libc++ IR"
mkdir -p "$dir/obj.goken"
dir=$(realpath "$dir")
# goken's 6c and 6l by full path (config.goken), not in PATH: its sed and
# other tools would shadow the system's, which the translation uses
export objtype=amd64

# the program's units and the libc++ modules they need
all=$dir/units
libs=$(python3 "$tu/libunits.py" $(cut -d' ' -f2 "$units") -- "$libir"/*.bc) ||
	fatal "cannot choose the library modules"
{
	cat "$units"
	for m in $libs; do
		echo "lib_$(basename "${m%.bc}") $m"
	done
} >"$all.new"
cmp -s "$all.new" "$all" || mv "$all.new" "$all"
rm -f "$all.new"
python3 "$tu/mkgen.py" "$all" "$dir" "$cbe" || fatal "mkgen failed"

# how each system compiles
cat >"$dir/config.goken.new" <<EOF
# generated by build.sh: do not edit
P0=$top
O=6
OBJ=obj.goken
TARG=$targ
CC=$goken/ROOT/arch/boot-gcc/bin/6c
LD=$goken/ROOT/arch/boot-gcc/bin/6l
CFLAGS=-w -I\$P0/plan9/shim
RTCFLAGS=-w -Damd64 -I$goken/include -I$goken/include/ALL -I$goken/include/arch/amd64 -I\$P0/eh -I\$P0/eh/plan9
LDFLAGS=-L$goken/ROOT/arch/amd64/lib -H7 -E _main
LIBS=-lc
RUNTIME=rt_p9 libc_p9 os_p9 net_none draw_none malloc_goken eh_rt
EOF
cat >"$dir/config.9front.new" <<EOF
# generated by build.sh: do not edit
</\$objtype/mkfile
P0=/n/ottd/phase0
OBJ=obj.9front
TARG=$targ
CFLAGS=-w -I\$P0/plan9/shim
RTCFLAGS=-w -I\$P0/eh -I\$P0/eh/plan9
LDFLAGS=
LIBS=
RUNTIME=rt_p9 libc_p9 os_p9 os9f net_p9 net9f draw_p9 kbd9f eh_rt
EOF
# Linux with its own C library (the fast loop for what libdraw does:
# plan9port's, through devdraw): the units' c_ names are the C
# library's again (unrename.h, from lower.py's list), except c_main,
# which main_unix.c calls after the constructors; the draw shim is
# compiled with the flags plan9port's 9c gives gcc.  The units' structs
# are packed, padded explicitly by cbe: 6c's #pragma pack on, which gcc
# ignores, is -fpack-struct
cat >"$dir/config.linux.new" <<EOF
# generated by build.sh: do not edit
P0=$top
P1=$(dirname "$top")/phase1
O=o
OBJ=obj.linux
TARG=$targ
CC=gcc -c
LD=gcc
CFLAGS=-w -O0 -std=gnu11 -fno-builtin -fpack-struct -include $dir/unrename.h
RTCFLAGS=-w -O0 -std=gnu11 -fno-omit-frame-pointer -fsigned-char -fno-common -I$PLAN9/include -I\$P0/eh -I\$P0/eh/unix
LDFLAGS=-L$PLAN9/lib
LIBS=-ldraw -lmux -l9 -lm -lpthread
RUNTIME=rt nothreads main_unix draw_p9 kbdp9p eh_rt
EOF
cat >"$dir/rules.linux.new" <<'EOF'
# generated by build.sh: do not edit
$OBJ/nothreads.$O: $P1/nothreads.c
	$CC $RTCFLAGS -o $target $prereq
EOF
for s in goken 9front; do
	echo '# generated by build.sh: no rules of its own' >"$dir/rules.$s.new"
done
python3 - "$top/plan9/lower.py" >"$dir/unrename.h.new" <<'EOF'
import re, sys
names = re.search(r'RENAMED = """(.*?)"""', open(sys.argv[1]).read(), re.S).group(1).split()
print("/* generated by build.sh: lower.py's c_ names, the C library's again */")
# glibc's math.h, which the units include, with the declarations that
# take pointers out of the way: cbe declares those with void*
ptr = "modf modff modfl frexp frexpf frexpl remquo remquof remquol lgamma_r lgammaf_r sincos sincosf".split()
for n in ptr:
	print("#define %s glibc_%s" % (n, n))
print("#include <math.h>")
for n in ptr:
	print("#undef %s" % n)
for n in names:
	if n != "main":
		print("#define c_%s %s" % (n, n))
EOF
for f in config.goken config.9front config.linux rules.goken rules.9front rules.linux unrename.h; do
	cmp -s "${dir:?}/$f.new" "$dir/$f" || mv "$dir/$f.new" "$dir/$f"
	rm -f "${dir:?}/${f:?}.new"
done

cd "$dir" || exit 1
"$mk" -f trans.mk syms >/dev/null || fatal "symbol tables failed"
python3 "$tu/homes.py" units . || fatal "homes failed"
# -k shows every failure; plan9port's mk -k then exits 0, so mk again
"$mk" -k -f trans.mk c
"$mk" -f trans.mk c >/dev/null || fatal "translation failed"
names=$(cut -d' ' -f1 units)
python3 "$tu/mergeinvoke.py" invoke.c $(printf '%s.inv ' $names) &&
python3 "$tu/mkctors.py" ctors.c $(printf '%s.ctors ' $names) || fatal "wrappers or constructors failed"
for s in ${sys:-goken}; do
	mkdir -p "obj.$s"
	# the commands in mk.$s.log; the failures shown
	"$mk" -k SYS=$s >"mk.$s.log" 2>&1
	"$mk" SYS=$s >>"mk.$s.log" 2>&1 || {
		grep -v '^warning' "mk.$s.log" | cut -c1-300 | tail -20
		fatal "compilation for $s failed"
	}
	echo "built $dir/obj.$s/$targ"
done
