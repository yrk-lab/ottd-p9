#!/usr/bin/env python3
# mkctors ctors.c unit.ctors...
#	The static constructor table of separately translated units:
#	__p9_ctors, which the runtime's main calls first, calls each unit's
#	exported constructors (lower.py --unit) by priority, lowest first,
#	and within a priority in the order of the units (link order).
#	ctors.c is written only if it changed.
import sys

if len(sys.argv) < 2:
	sys.exit("usage: mkctors ctors.c unit.ctors...")
calls = []
for i, f in enumerate(sys.argv[2:]):
	for line in open(f):
		p, name = line.split()
		calls.append((int(p), i, name))
calls.sort()
out = ["/* generated by mkctors.py: do not edit */\n"]
out += ["void %s(void);\n" % c[2] for c in calls]
out.append("\nvoid\n__p9_ctors(void)\n{\n")
out += ["\t%s();\n" % c[2] for c in calls]
out.append("}\n")
new = "".join(out)
try:
	old = open(sys.argv[1]).read()
except FileNotFoundError:
	old = None
if new != old:
	open(sys.argv[1], "w").write(new)
